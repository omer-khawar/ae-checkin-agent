#!/usr/bin/env node
/**
 * Regenerates `plainLanguageTable.ts` from `packages/rules/data/plain_language.json`
 * (CONTRACTS.md R3.1). Run from apps/web:
 *
 *   node src/pages/dashboard/detail/genPlainLanguageTable.mjs
 *
 * The output is formatted with the repo's Prettier when it is installed. The
 * vitest `plainLanguageTable.test.ts` fails whenever the TS copy drifts from the
 * JSON, so a changed table is caught in CI rather than at demo time.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const jsonPath = resolve(here, "../../../../../../packages/rules/data/plain_language.json");
const outPath = resolve(here, "plainLanguageTable.ts");
const table = JSON.parse(readFileSync(jsonPath, "utf8"));

const fields = Object.fromEntries(
  Object.entries(table.fields).map(([k, v]) => [k, typeof v === "string" ? v : v.label]),
);
const rules = Object.fromEntries(
  Object.entries(table.rules).map(([k, v]) => [k, { sentence: v.sentence, fallback: v.fallback }]),
);
const j = (v) => JSON.stringify(v, null, 2);

const src = `/**
 * Local fallback copy of \`packages/rules/data/plain_language.json\` (CONTRACTS.md R3.1).
 *
 * GENERATED by \`genPlainLanguageTable.mjs\` in this folder (fields, rules, tiers, grades,
 * clock kinds, evidence kinds, domains, input aliases, render_as). The API's own
 * \`labels\` map (GET /checkins/{id} \`.labels\`, R3.2) and any \`plain\` sentence it attaches
 * to a rule always win; this copy only keeps the page plain-language-first when the API
 * is older or the field is new. Do not hand-edit: run
 * \`node src/pages/dashboard/detail/genPlainLanguageTable.mjs\` from apps/web.
 * \`__tests__/plainLanguageTable.test.ts\` fails when this copy drifts from the JSON.
 */

export const PLAIN_FIELDS: Record<string, string> = ${j(fields)};

export const PLAIN_RULES: Record<string, { sentence: string; fallback: string }> = ${j(rules)};

export const PLAIN_INPUT_ALIASES: Record<string, string[]> = ${j(table.input_aliases)};

export const PLAIN_RENDER_AS: Record<string, "field_label" | "item_label"> = ${j(table.render_as)};

export const PLAIN_TIERS: Record<string, string> = ${j(table.tiers)};

export const PLAIN_GRADES: Record<string, string> = ${j(table.grades)};

export const PLAIN_CLOCK_KINDS: Record<
  string,
  { name: string; protocol_ref: { section: string; printed_page: number }; note: string }
> = ${j(table.clock_kinds)};

export const PLAIN_EVIDENCE_KINDS: Record<string, string> = ${j(table.evidence_kinds)};

export const PLAIN_DOMAINS: Record<string, string> = ${j(table.domains)};
`;

let out = src;
try {
  const prettier = await import("prettier");
  const config = (await prettier.resolveConfig(outPath)) ?? {};
  out = await prettier.format(src, { ...config, filepath: outPath });
} catch {
  // Prettier not installed: the unformatted output is still valid TypeScript.
}
writeFileSync(outPath, out, "utf8");
console.log(
  `wrote ${outPath} (${Object.keys(fields).length} fields, ${Object.keys(rules).length} rules)`,
);
