/**
 * The participant's background chart from Synthea (synthetic EHR), as the API
 * returns it on `GET /participants/{usubjid}/timeline` and `/brief` under
 * `baseline`. Every value here is simulated: the card says so in its title, in
 * a SIMULATED badge, and in the footnote, so a screenshot cannot be mistaken
 * for a real chart.
 *
 * The payload shape is read defensively (`normalizeBaseline` in ./baseline):
 * an absent or malformed baseline renders nothing rather than a broken card.
 */
import { MeasuredBadge } from "../../../components/MeasuredBadge";
import { type BaselineVital, normalizeBaseline } from "./baseline";

function withSimulated(label: string): string {
  return /simulated/i.test(label) ? label : `${label} (simulated)`;
}

function vitalText(v: BaselineVital | null): string {
  if (!v) return "—";
  const n = v.n_observations;
  return `${v.median} ${v.unit}${n > 0 ? ` (median of ${n} visit${n === 1 ? "" : "s"})` : ""}`;
}

export function BaselineCard({ baseline, className }: { baseline: unknown; className?: string }) {
  const b = normalizeBaseline(baseline);
  if (!b) return null;
  const who = [b.age_at_reference !== null ? `${b.age_at_reference}-year-old` : null, b.sex]
    .filter(Boolean)
    .join(" ");
  const rows: Array<[string, string]> = [
    ["Patient", who || "—"],
    [
      "Diagnosis",
      b.nsclc_display
        ? `${b.nsclc_display}${b.nsclc_diagnosis_date ? `, diagnosed ${b.nsclc_diagnosis_date}` : ""}`
        : "—",
    ],
    ["Baseline pulse", vitalText(b.pulse_bpm)],
    ["Baseline breathing", vitalText(b.breathing_bpm)],
    ["Other conditions", b.comorbidities.join("; ") || "—"],
    ["Medications on record", b.active_medications.join(", ") || "—"],
    ["Earlier cancer therapy", b.prior_cancer_therapy.join(", ") || "—"],
    ["Smoking", b.smoking ?? "—"],
  ];
  return (
    <section
      className={`rounded-panel border border-border bg-surface ${className ?? ""}`}
      data-testid="synthea-baseline"
    >
      <header className="flex min-h-row items-center justify-between gap-3 border-b border-border px-3 py-1.5">
        <h2 className="text-body font-semibold text-foreground">Background chart</h2>
        {
          <span className="flex items-center gap-1.5 text-caption text-muted-foreground">
            <MeasuredBadge isMeasured={false} source="synthea" />
          </span>
        }
      </header>
      <div className="p-3">
        <p className="text-table font-medium text-simulated-fg">{withSimulated(b.label)}</p>
        <dl className="mt-2 grid gap-x-6 gap-y-1 text-table text-muted-foreground sm:grid-cols-[auto_1fr]">
          {rows.map(([k, v]) => (
            <div key={k} className="contents">
              <dt className="font-medium text-muted-foreground">{k}</dt>
              <dd className="text-foreground">{v}</dd>
            </div>
          ))}
        </dl>
        <p className="mt-3 text-caption text-muted-foreground">
          Generated by Synthea, an open-source synthetic patient generator
          {b.synthea_ref ? (
            <>
              {" "}
              (record <span className="font-mono">{b.synthea_ref}</span>)
            </>
          ) : null}
          . No real person; every value here is simulated. The baseline pulse and breathing are the
          reference the kiosk&apos;s simulated resting vitals are drawn around.
        </p>
      </div>
    </section>
  );
}
